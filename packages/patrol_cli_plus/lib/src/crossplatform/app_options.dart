class FlutterAppOptions {
  const FlutterAppOptions({
    required this.command,
    required this.target,
    required this.flavor,
    required this.buildMode,
    required this.dartDefines,
    required this.dartDefineFromFilePaths,
    required this.buildName,
    required this.buildNumber,
    this.noTreeShakeIcons = false,
  });

  final FlutterCommand command;
  final String target;
  final String? flavor;
  final BuildMode buildMode;
  final Map<String, String> dartDefines;
  final List<String> dartDefineFromFilePaths;
  final String? buildName;
  final String? buildNumber;
  final bool noTreeShakeIcons;

  /// Translates these options into a proper `flutter attach`.
  @nonVirtual
  List<String> toFlutterAttachInvocation() {
    final cmd = [
      ...[command.executable, ...command.arguments],
      'attach',
      '--no-version-check',
      '--suppress-analytics',
      '--debug',
      ...['--target', target],
      for (final dartDefine in dartDefines.entries) ...[
        '--dart-define',
        '${dartDefine.key}=${dartDefine.value}',
      ],
      for (final dartDefineFromFilePath in dartDefineFromFilePaths) ...[
        '--dart-define-from-file',
        dartDefineFromFilePath,
      ],
    ];

    return cmd;
  }

  /// Translates these options into a host `flutter test` invocation that runs
  /// the bundle in build-time discovery mode and writes the test manifest to
  /// [manifestOutputPath].
  ///
  /// The same `--dart-define`s as the real build are forwarded on purpose: a
  /// test description can be built from a dart-define (e.g. a target env), so
  /// discovery must see the exact same config or the manifest names would
  /// diverge from what the on-device run registers.
  ///
  /// Only the internal `patrol_test_explorer` test is allowed to run
  /// (`--plain-name`). Declaring the tests is what builds the group tree, so the
  /// manifest stays complete, but nothing else is *scheduled* - which means no
  /// `setUp`/`tearDown`/`setUpAll`/`tearDownAll` around the user's tests ever
  /// executes during discovery. That holds regardless of how those hooks were
  /// registered (plain `setUp`, `patrolSetUp`, or a project's own wrapper), so
  /// device-dependent fixtures can't break the host discovery run.
  @nonVirtual
  List<String> toFlutterTestDiscoveryInvocation({
    required String manifestOutputPath,
  }) {
    return [
      ...[command.executable, ...command.arguments],
      'test',
      target,
      '--suppress-analytics',
      // Keep in sync with the explorer test name emitted by TestBundler.
      ...['--plain-name', 'patrol_test_explorer'],
      ...['--dart-define', 'PATROL_TEST_DISCOVERY=true'],
      ...['--dart-define', 'PATROL_MANIFEST_OUTPUT=$manifestOutputPath'],
      for (final dartDefine in dartDefines.entries) ...[
        '--dart-define',
        '${dartDefine.key}=${dartDefine.value}',
      ],
      for (final dartDefineFromFilePath in dartDefineFromFilePaths) ...[
        '--dart-define-from-file',
        dartDefineFromFilePath,
      ],
    ];
  }
}

/// The environment variable [AndroidAppOptions.toGradleDartDefinesEnvironment]
/// uses to carry the `dart-defines` payload. MUST be a valid shell
/// identifier -- see that method's doc comment for why.
const dartDefinesGradleEnvVar = 'PATROL_GRADLE_DART_DEFINES';

/// Contents of the Gradle `--init-script` that reads
/// [dartDefinesGradleEnvVar] and sets it as the `dart-defines` project
/// property Flutter's Gradle plugin reads, before any project's own
/// `build.gradle` (and therefore `apply plugin:
/// "dev.flutter.flutter-gradle-plugin"`) is evaluated.
///
/// `gradle.beforeProject` fires immediately before each project is
/// evaluated -- i.e. before that project's build script, including its
/// `apply plugin` lines, has run -- so the `dart-defines` extra property is
/// in place well before `FlutterPlugin`'s own property read (which happens
/// later still, in a lazy `applicationVariants.configureEach` callback that
/// AGP invokes after the whole project has been evaluated). Verified live
/// against real Gradle 8.14.3 on Linux (dash) and Windows: the value tracks
/// correctly across repeated invocations against a REUSED daemon (no
/// staleness), including when the invoking shell is dash.
const dartDefinesGradleInitScriptContents =
    '''
// Generated by patrol_cli_plus. Forwards the "dart-defines" Gradle project
// property through an environment variable with a valid identifier name.
//
// ORG_GRADLE_PROJECT_<name> -- Gradle's own project-property-via-env
// convention -- is NOT used here because "dart-defines" contains a dash,
// which is not a valid shell/environment-variable identifier character. On
// Linux and macOS, Process.start(runInShell: true) runs the child through
// /bin/sh; where /bin/sh is dash (e.g. Ubuntu, Debian), dash drops any
// environment variable with an invalid name before gradlew (itself a
// #!/bin/sh script) ever sees it, silently losing every dart-define. bash
// (macOS's /bin/sh) does not have this problem, but relying on that would
// make the fix shell-dependent. See PR #67 on Bdaya-Dev/patrol for the live
// probe. This script uses a valid name and sets the "dart-defines" project
// property directly instead, which works identically on every shell.
gradle.beforeProject { project ->
    def dartDefinesValue = System.getenv("$dartDefinesGradleEnvVar")
    if (dartDefinesValue != null) {
        project.ext.set("dart-defines", dartDefinesValue)
    }
}
''';

class AndroidAppOptions {
  const AndroidAppOptions({
    required this.flutter,
    this.packageName,
    required this.appServerPort,
    required this.testServerPort,
    required this.uninstall,
    this.emitTestManifest = false,
    this.extraDartDefinesFromFile = const {},
  });

  final FlutterAppOptions flutter;
  final String? packageName;
  final int appServerPort;
  final int testServerPort;
  final bool uninstall;

  /// Whether to discover Dart tests at build time (host `flutter test`) and
  /// generate static JUnit test methods, so each Dart test becomes a real,
  /// individually-selectable native test. Experimental, opt-in.
  final bool emitTestManifest;

  /// The contents of `--dart-define-from-file` (and, separately, the
  /// implicit `.patrol.env`), decoded. SEPARATE from [flutter]'s own
  /// `dartDefines` -- which is the map every OTHER platform (iOS, macOS,
  /// web, desktop, `flutter attach`, host test discovery) forwards to
  /// Flutter's own `--dart-define`/`--dart-define-from-file` flags, where
  /// Flutter itself reads the file and these values never touch patrol's
  /// argv. Gradle has no equivalent of `--dart-define-from-file`: its ONLY
  /// define channel is the `dart-defines` project property (see
  /// [toGradleDartDefinesEnvironment]), so these values must be folded in
  /// there instead, delivered via environment rather than argv.
  final Map<String, String> extraDartDefinesFromFile;

  String get description => 'apk with entrypoint ${basename(flutter.target)}';

  /// The [dartDefinesGradleEnvVar] environment variable Gradle needs to
  /// receive the same `dart-defines` project property that used to be
  /// passed as `-Pdart-defines=<base64>` on this process's own argv
  /// (readable by any local process via `ps`/Task Manager).
  ///
  /// Gradle resolves a project property from either `-P<name>=value` on its
  /// command line OR an `ORG_GRADLE_PROJECT_<name>` environment variable --
  /// see
  /// https://docs.gradle.org/current/userguide/build_environment.html#sec:project_properties
  /// -- but `ORG_GRADLE_PROJECT_dart-defines` is not usable: `dart-defines`
  /// contains a dash, which is not a valid identifier, and on Linux/macOS
  /// `Process.start(runInShell: true)` runs the child through `/bin/sh`;
  /// where `/bin/sh` is dash (Ubuntu, Debian, ...), dash drops any
  /// environment variable with an invalid name before `gradlew` (itself a
  /// `#!/bin/sh` script) ever sees it, losing every define. The caller must
  /// instead merge this into the environment of whatever process runs a
  /// Gradle invocation returned by [toGradleAssembleInvocation] /
  /// [toGradleAssembleTestInvocation] / [toGradleConnectedTestInvocation],
  /// AND pass that same invocation's `dartDefinesGradleInitScriptPath`
  /// parameter as a path to [dartDefinesGradleInitScriptContents] written to
  /// disk, which reads this valid-identifier variable and sets the
  /// `dart-defines` project property directly. None of the three invocation
  /// methods add `-Pdart-defines` to argv any more.
  ///
  /// File entries come FIRST and `flutter.dartDefines` (CLI `--dart-define`
  /// plus patrol's own internal defines) come LAST, so a CLI/internal entry
  /// overrides a file entry with the same key -- matching Flutter's own
  /// `--dart-define-from-file` precedence ("Entries from `--dart-define`
  /// with identical keys take precedence over entries from these files"),
  /// so Android behaves the same as every other platform.
  Map<String, String> toGradleDartDefinesEnvironment() {
    final effectiveDartDefines = {
      ...extraDartDefinesFromFile,
      ...flutter.dartDefines,
    };
    if (effectiveDartDefines.isEmpty) {
      return const {};
    }

    final dartDefinesString = StringBuffer();
    for (var i = 0; i < effectiveDartDefines.length; i++) {
      final entry = effectiveDartDefines.entries.elementAt(i);
      final pair = utf8.encode('${entry.key}=${entry.value}');
      dartDefinesString.write(base64Encode(pair));
      if (i != effectiveDartDefines.length - 1) {
        dartDefinesString.write(',');
      }
    }

    return {dartDefinesGradleEnvVar: dartDefinesString.toString()};
  }

  List<String> toGradleAssembleInvocation({
    required bool isWindows,
    String? dartDefinesGradleInitScriptPath,
  }) {
    // for example: assembleDevDebug, assembleRelease
    return _toGradleInvocation(
      isWindows: isWindows,
      task: 'assemble$_effectiveFlavor$_buildMode',
      dartDefinesGradleInitScriptPath: dartDefinesGradleInitScriptPath,
    );
  }

  List<String> toGradleAssembleTestInvocation({
    required bool isWindows,
    String? dartDefinesGradleInitScriptPath,
  }) {
    // for example: assembleDevDebugAndroidTest, assembleReleaseAndroidTest
    return _toGradleInvocation(
      isWindows: isWindows,
      task: 'assemble$_effectiveFlavor${_buildMode}AndroidTest',
      noUninstallAfterTests: !uninstall,
      dartDefinesGradleInitScriptPath: dartDefinesGradleInitScriptPath,
    );
  }

  List<String> toGradleConnectedTestInvocation({
    required bool isWindows,
    String? onlyTestClass,
    String? dartDefinesGradleInitScriptPath,
  }) {
    // for example: connectedDevDebugAndroidTest, connectedReleaseAndroidTest
    return _toGradleInvocation(
      isWindows: isWindows,
      task: 'connected$_effectiveFlavor${_buildMode}AndroidTest',
      noUninstallAfterTests: !uninstall,
      // Restrict the run to the generated static class (the Android analog of
      // iOS `-only-testing`). This also stops the parameterized host class from
      // performing its runtime discovery launch.
      onlyTestClass: onlyTestClass,
      dartDefinesGradleInitScriptPath: dartDefinesGradleInitScriptPath,
    );
  }

  List<String> toGradleAppDependencies({required bool isWindows}) {
    final List<String> cmd;
    if (isWindows) {
      cmd = <String>[r'.\gradlew.bat'];
    } else {
      cmd = <String>['./gradlew'];
    }

    // Add Gradle task
    cmd.add(':app:dependencies');

    return cmd;
  }

  String get _buildMode => flutter.buildMode.androidName;

  String get _effectiveFlavor {
    var flavor = flutter.flavor ?? '';
    if (flavor.isNotEmpty) {
      flavor = flavor[0].toUpperCase() + flavor.substring(1);
    }
    return flavor;
  }

  /// Translates these options into a proper Gradle invocation.
  List<String> _toGradleInvocation({
    required bool isWindows,
    required String task,
    bool noUninstallAfterTests = false,
    String? onlyTestClass,
    String? dartDefinesGradleInitScriptPath,
  }) {
    final List<String> cmd;
    if (isWindows) {
      cmd = <String>[r'.\gradlew.bat'];
    } else {
      cmd = <String>['./gradlew'];
    }

    // Deliver dart-defines via --init-script (reading the valid-identifier
    // dartDefinesGradleEnvVar from the environment) rather than -P on argv
    // -- see toGradleDartDefinesEnvironment's doc comment. The caller must
    // ALSO merge toGradleDartDefinesEnvironment() into this invocation's
    // environment for the init script to have anything to read.
    if (dartDefinesGradleInitScriptPath != null) {
      cmd.addAll(['--init-script', dartDefinesGradleInitScriptPath]);
    }

    // Add Gradle task
    cmd.add(':app:$task');

    // Add Dart test target
    final target = '-Ptarget=${flutter.target}';
    cmd.add(target);

    // SECURITY: dart-defines are deliberately NOT added to argv here --
    // see toGradleDartDefinesEnvironment's doc comment. The caller must
    // merge that into this invocation's environment instead.

    /// In Android Gradle Plugin 8.1.0 default behaviour has been changed
    /// and the application is uninstalled after integration tests.
    /// An issue has been reported:
    /// AGP 8.1.0 uninstalls app after running instrumented tests - 7.4.2 does not:
    /// https://issuetracker.google.com/issues/295039976
    /// New solution to change this behaviour has been introduced in AGP 8.2.0:
    /// https://developer.android.com/build/releases/past-releases/agp-8-2-0-release-notes
    ///
    /// To keep the app installed after the test finishes on Android
    /// with AGP 8.2 or higher, add in `gradle.properties`:
    /// ```
    /// android.injected.androidTest.leaveApksInstalledAfterRun=true
    /// ```
    if (noUninstallAfterTests) {
      cmd.add('-Pandroid.injected.androidTest.leaveApksInstalledAfterRun=true');
    }

    // Ports for the native automator servers, plus a flag apps can use to
    // detect a Patrol Gradle build.
    cmd
      ..add('-Papp-server-port=$appServerPort')
      ..add('-Ptest-server-port=$testServerPort')
      ..add('-Ppatrol-enabled=true');

    // Run only the generated static test class, if requested.
    if (onlyTestClass != null) {
      cmd.add(
        '-Pandroid.testInstrumentationRunnerArguments.class=$onlyTestClass',
      );
    }

    return cmd;
  }
}

class IOSAppOptions {
  IOSAppOptions({
    required this.flutter,
    this.bundleId,
    required this.scheme,
    required this.configuration,
    required this.simulator,
    required this.osVersion,
    required this.appServerPort,
    required this.testServerPort,
    this.fullIsolation = false,
    this.clearIOSPermissions = false,
    this.emitTestManifest = false,
  });

  final FlutterAppOptions flutter;
  final String? bundleId;
  final String scheme;
  final String configuration;
  final String osVersion;
  final bool simulator;
  final int appServerPort;
  final int testServerPort;
  final bool fullIsolation;
  final bool clearIOSPermissions;

  /// Whether to discover Dart tests at build time (host `flutter test`) and
  /// embed a manifest into the test bundle, so the native runner can skip the
  /// runtime discovery launch. Experimental, opt-in.
  final bool emitTestManifest;

  String get description {
    final platform = simulator ? 'simulator' : 'device';
    return 'app with entrypoint ${basename(flutter.target)} for iOS $platform';
  }

  /// Translates these options into a proper flutter build invocation, which
  /// runs before xcodebuild and performs configuration.
  List<String> toFlutterBuildInvocation(BuildMode buildMode) {
    final cmd = [
      ...[flutter.command.executable, ...flutter.command.arguments],
      ...['build', 'ios'],
      '--no-version-check',
      '--suppress-analytics',
      ...[
        '--config-only',
        '--no-codesign',
        '--${buildMode.name}', // for example '--debug',
        if (simulator) '--simulator',
        if (flutter.noTreeShakeIcons) '--no-tree-shake-icons',
      ],
      if (flutter.flavor case final flavor?) ...['--flavor', flavor],
      if (flutter.buildName case final buildName?) ...[
        '--build-name',
        buildName,
      ],
      if (flutter.buildNumber case final buildNumber?) ...[
        '--build-number',
        buildNumber,
      ],
      ...['--target', flutter.target],
      for (final dartDefine in flutter.dartDefines.entries) ...[
        '--dart-define',
        '${dartDefine.key}=${dartDefine.value}',
      ],
      for (final dartDefineFromFilePath in flutter.dartDefineFromFilePaths) ...[
        '--dart-define-from-file',
        dartDefineFromFilePath,
      ],
    ];

    return cmd;
  }

  /// Translates these options into a proper `xcodebuild build-for-testing`
  /// invocation.
  List<String> buildForTestingInvocation() {
    final cmd = [
      ...['xcodebuild', 'build-for-testing'],
      ...['-workspace', 'Runner.xcworkspace'],
      ...['-scheme', scheme],
      ...['-configuration', configuration],
      ...['-sdk', if (simulator) 'iphonesimulator' else 'iphoneos'],
      ...[
        '-destination',
        'generic/platform=${simulator ? 'iOS Simulator' : 'iOS'}',
      ],
      '-quiet',
      ...['-derivedDataPath', '../build/ios_integ'],
      r'OTHER_SWIFT_FLAGS=$(inherited) -D PATROL_ENABLED',
      r'OTHER_LDFLAGS=$(inherited) -weak_framework XCTest -F$(PLATFORM_DIR)/Developer/Library/Frameworks -L$(PLATFORM_DIR)/Developer/usr/lib',
      'OTHER_CFLAGS=\$(inherited) -D FULL_ISOLATION=${fullIsolation ? 1 : 0} -D CLEAR_PERMISSIONS=${clearIOSPermissions ? 1 : 0}',
    ];

    return cmd;
  }

  /// Translates these options into a proper `xcodebuild test-without-building`
  /// invocation.
  ///
  /// When [onlyTesting] is non-empty, one `-only-testing` selector is emitted per
  /// entry (`RunnerUITests/RunnerUITests/<selector>`), restricting the run to
  /// those specific generated tests; otherwise the whole `RunnerUITests` class
  /// runs. Per-test selectors require the static codegen (build-time discovery).
  List<String> testWithoutBuildingInvocation(
    Device device, {
    required String xcTestRunPath,
    required String resultBundlePath,
    List<String> onlyTesting = const [],
  }) {
    // Target simulators by their exact UDID. The previous
    // `platform=iOS Simulator,OS=$osVersion,name=$name` specifier failed to
    // resolve a booted simulator ("xcodebuild: error: Unable to find a
    // device matching the provided destination specifier" -> exit 70) when
    // OS was `latest` or the runtime enumeration was slow on CI; `id=<udid>`
    // is unambiguous and resolves instantly. Real devices are addressed by
    // `platform=iOS,id=<id>` so that device names containing commas cannot
    // break the specifier. `osVersion` (the `--ios` flag) is retained for
    // backward compatibility but is no longer used for simulators.
    final destination = device.real
        ? 'platform=iOS,id=${device.id}'
        : 'id=${device.id}';

    final cmd = [
      ...['xcodebuild', 'test-without-building'],
      ...['-xctestrun', xcTestRunPath],
      if (onlyTesting.isEmpty) ...[
        '-only-testing',
        'RunnerUITests/RunnerUITests',
      ] else
        for (final selector in onlyTesting) ...[
          '-only-testing',
          'RunnerUITests/RunnerUITests/$selector',
        ],
      ...['-destination', destination],
      ...['-destination-timeout', _iosDestinationTimeoutSeconds()],
      ...['-resultBundlePath', resultBundlePath],
    ];

    return cmd;
  }
}

/// The `-destination-timeout` value (in seconds) for `xcodebuild
/// test-without-building` when targeting a booted simulator by its UDID.
///
/// Resolving a freshly-booted simulator can take several seconds on slow or
/// first-boot CI images (notably the macOS 26 / Xcode 26 runner, where the
/// initial CoreSimulator/CoreDevice enumeration is slow), so the previous
/// hardcoded `1` produced spurious "Unable to find a device matching the
/// provided destination specifier" (exit 70) failures even though the device
/// was already booted. Defaults to `30`; override with the
/// `PATROL_DESTINATION_TIMEOUT` environment variable (a positive integer
/// number of seconds).
String _iosDestinationTimeoutSeconds() {
  final raw = Platform.environment['PATROL_DESTINATION_TIMEOUT'];
  if (raw != null) {
    final parsed = int.tryParse(raw.trim());
    if (parsed != null && parsed > 0) {
      return parsed.toString();
    }
  }
  return '30';
}

